#!/usr/bin/env python3
"""Builds the two files the kit assembler reads, from the sources in this folder.

The page script and the card artboard cannot share code through the kit, and
both need the chart engine, so engine.js is pasted into each:

  section.js        = engine.js + page.js
  card.src.dc.html  = card.tpl.html with engine.js and card.js pasted in

Edit the sources, run this, then run kit/assemble.py. Run from anywhere."""
import os

here = os.path.dirname(os.path.abspath(__file__))
read = lambda name: open(os.path.join(here, name)).read()
NOTE = '// Generated by build.py from engine.js and {}. Edit those, not this file.\n'

engine, page, card = read('engine.js'), read('page.js'), read('card.js')

open(os.path.join(here, 'section.js'), 'w').write(NOTE.format('page.js') + engine + '\n' + page)

tpl = read('card.tpl.html')
tpl = tpl.replace('/*ENGINE_JS*/', engine.rstrip('\n')).replace('/*CARD_JS*/', NOTE.format('card.js') + card.rstrip('\n'))
open(os.path.join(here, 'card.src.dc.html'), 'w').write(tpl)
print('built section.js and card.src.dc.html')
